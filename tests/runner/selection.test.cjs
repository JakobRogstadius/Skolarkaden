// Real Git history: committed branch changes, renames, staged/unstaged edits,
// deletion and new files must all contribute, including filenames with spaces.
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'skolarkaden-selection-'));
const git=(...args)=>execFileSync('git',args,{cwd:temp,encoding:'utf8',stdio:['ignore','pipe','pipe']});
const write=(name,text)=>{fs.mkdirSync(path.dirname(path.join(temp,name)),{recursive:true});fs.writeFileSync(path.join(temp,name),text);};
try{
 git('init','-b','main');git('config','user.email','tests@example.invalid');git('config','user.name','Selection test');
 const html='<script src="resources/app.js?v=aaaaaaaaaaaa"></script>';
 for(const file of ['branch.js','stage.js','work.js','delete.js','rename.js'])write(file,'original\n');
 write('index.html',html);git('add','.');git('commit','-m','base');
 git('switch','-c','feature');write('branch.js','committed\n');git('add','branch.js');git('commit','-m','branch change');
 write('stage.js','staged\n');git('add','stage.js');write('work.js','unstaged\n');
 fs.unlinkSync(path.join(temp,'delete.js'));git('mv','rename.js','renamed file.js');write('new file.js','new\n');
 write('index.html',html.replace('aaaaaaaaaaaa','bbbbbbbbbbbb'));
 const change=changedFiles({cwd:temp});
 assert.deepEqual(change.files,['branch.js','delete.js','index.html','new file.js','rename.js','renamed file.js','stage.js','work.js']);
 assert(change.assetOnly.has('index.html'));
 write('index.html','<main>structural edit</main>'+html);git('add','index.html');write('index.html',html);
 assert(!changedFiles({cwd:temp}).assetOnly.has('index.html'),'staged structure cannot be hidden by unstaged restoration');
 assert.throws(()=>changedFiles({cwd:temp,base:'missing-branch'}),/Cannot resolve/);
 // Missing a conventional main ref is conservative, not zero tests.
 git('branch','-m','main','trunk');assert(changedFiles({cwd:temp}).fallback);
}finally{fs.rmSync(temp,{recursive:true,force:true});}
console.log('PASS dependency selection, game filtering, safe fallbacks, CLI validation and real Git changes');
